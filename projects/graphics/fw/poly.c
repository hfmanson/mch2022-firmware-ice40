/* cos(x) = sin(x + 90°) */
#define MASK (TABLE_SIZE - 1)
#define COS(a) sintab[((a) + (TABLE_SIZE / 4)) & MASK]
#define SIN(a) sintab[(a) & MASK]

#define MAX_SIDES 30

int x[MAX_SIDES];
int y[MAX_SIDES];

void draw_polygon(int sides, int radius, int angle, uint16_t color)
{
    int i, j;

    int step = TABLE_SIZE / sides;
	
    for (i = 0; i < sides; i++)
    {
        x[i] = CENTER_X + ((COS(angle) * radius) >> 12);
        y[i] = CENTER_Y + ((SIN(angle) * radius) >> 12);
		angle += step;
	}
    for (i = 0; i < sides - 1; i++)
    {
		int xi = x[i];
		int yi = y[i];
		for (j = i + 1; j < sides; j++)
		{
            draw_line(xi, yi, x[j], y[j], color);
		}
	}	
}
